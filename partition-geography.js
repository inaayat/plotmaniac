export function cameraBox(name) {
  const box = CAMERAS[name] || CAMERAS.all;
  const [minLon, minLat, maxLon, maxLat] = box;
  const [x0, yBottom] = project(minLon, minLat);
  const [x1, yTop] = project(maxLon, maxLat);
  const pad = name === "all" ? 8 : 26;
  return [x0 - pad, yTop - pad, (x1 - x0) + pad * 2, (yBottom - yTop) + pad * 2];
}

